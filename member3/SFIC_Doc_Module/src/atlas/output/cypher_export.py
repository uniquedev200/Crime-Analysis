"""Neo4j Cypher text export for ATLAS Dev 3 graph payloads.

Implements PLAN.md Section 4.6 and J4 specifications:
- Generates valid Neo4j Cypher script using MERGE statements for nodes and relationships.
- All properties properly escaped (no database connection needed).
- Deterministic output (nodes sorted by node_id, edges sorted by edge_id).
"""

from __future__ import annotations

import re
from typing import Any


def _escape_prop_key(key: str) -> str:
    """Sanitize property or label key for Cypher syntax."""
    # If key contains non-alphanumeric chars, backtick escape it
    if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", key):
        return key
    sanitized = key.replace("`", "")
    return f"`{sanitized}`"


def _cypher_literal(val: Any) -> str:
    """Format Python value as Cypher literal."""
    if val is None:
        return "null"
    if isinstance(val, bool):
        return "true" if val else "false"
    if isinstance(val, (int, float)):
        return str(val)
    if isinstance(val, (list, tuple, set)):
        items = ", ".join(_cypher_literal(x) for x in sorted(list(val), key=lambda x: str(x)))
        return f"[{items}]"
    if isinstance(val, dict):
        parts = [f"{_escape_prop_key(k)}: {_cypher_literal(v)}" for k, v in sorted(val.items())]
        return "{" + ", ".join(parts) + "}"
    # String
    s = str(val)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f"'{s}'"


def export_cypher(graph_payload: dict[str, Any]) -> str:
    """Export graph payload to deterministic Neo4j Cypher MERGE script.

    Args:
        graph_payload: Dictionary containing 'nodes' and 'edges'.

    Returns:
        Deterministic Cypher script string.
    """
    nodes = list(graph_payload.get("nodes", []))
    edges = list(graph_payload.get("edges", []))

    # Sort deterministically
    sorted_nodes = sorted(nodes, key=lambda n: n.get("node_id", ""))
    sorted_edges = sorted(edges, key=lambda e: e.get("edge_id", ""))

    lines: list[str] = [
        "// Cypher export generated by ATLAS Dev 3",
        "// Deterministic MERGE statements for nodes and relationships",
        "",
        f"// Nodes ({len(sorted_nodes)})",
    ]

    for node in sorted_nodes:
        node_id = node.get("node_id", "")
        label = node.get("label", "Entity")
        escaped_label = _escape_prop_key(label)

        set_clauses: list[str] = [
            f"n.canonical = {_cypher_literal(node.get('canonical', True))}",
            f"n.case_ids = {_cypher_literal(node.get('case_ids', []))}",
            f"n.evidence_ids = {_cypher_literal(node.get('evidence_ids', []))}",
        ]

        props = node.get("props", {})
        if isinstance(props, dict):
            for pk, pv in sorted(props.items()):
                # Skip duplicate node_id in props
                if pk == "node_id":
                    continue
                set_clauses.append(f"n.{_escape_prop_key(pk)} = {_cypher_literal(pv)}")

        set_str = ",\n    ".join(set_clauses)
        statement = f"MERGE (n:{escaped_label} {{node_id: {_cypher_literal(node_id)}}})\nSET {set_str};"
        lines.append(statement)

    lines.append("")
    lines.append(f"// Edges ({len(sorted_edges)})")

    for edge in sorted_edges:
        edge_id = edge.get("edge_id", "")
        edge_type = edge.get("type", "RELATED_TO")
        src = edge.get("src", "")
        dst = edge.get("dst", "")
        escaped_type = _escape_prop_key(edge_type)

        set_clauses = [
            f"r.canonical = {_cypher_literal(edge.get('canonical', True))}",
            f"r.assertion = {_cypher_literal(edge.get('assertion', 'stated'))}",
            f"r.origin = {_cypher_literal(edge.get('origin', 'unknown'))}",
            f"r.case_ids = {_cypher_literal(edge.get('case_ids', []))}",
            f"r.evidence_ids = {_cypher_literal(edge.get('evidence_ids', []))}",
        ]

        props = edge.get("props", {})
        if isinstance(props, dict):
            for pk, pv in sorted(props.items()):
                if pk == "edge_id":
                    continue
                set_clauses.append(f"r.{_escape_prop_key(pk)} = {_cypher_literal(pv)}")

        set_str = ",\n    ".join(set_clauses)
        statement = (
            f"MATCH (src {{node_id: {_cypher_literal(src)}}}), (dst {{node_id: {_cypher_literal(dst)}}})\n"
            f"MERGE (src)-[r:{escaped_type} {{edge_id: {_cypher_literal(edge_id)}}}]->(dst)\n"
            f"SET {set_str};"
        )
        lines.append(statement)

    lines.append("")
    return "\n".join(lines)


__all__ = ["export_cypher"]
